import assert from 'node:assert/strict';
import {ensureCloudCalendar,resolveCalendarAnchor} from '../luxury-v2/cloud-calendar.mjs';
import {dateKey} from '../luxury-v2/calendar-weeks.mjs';
const now=new Date(2026,10,1,12);
const oldAnchor=new Date(2026,9,25,12);
assert.equal(dateKey(resolveCalendarAnchor('2026-10-25',new Date(2026,10,1),now).anchor),'2026-10-25');
assert.equal(dateKey(resolveCalendarAnchor(null,oldAnchor,now).anchor),'2026-10-25');
assert.equal(dateKey(resolveCalendarAnchor(null,null,now).anchor),'2026-11-01');
const record={activePlanningWeek:2,plan:{0:[null,null,'tacos',null]},alternateWeek:{plan:{}}};
const originalPlan=JSON.stringify(record.plan);let updates=[];
const tx={get:async()=>({exists:()=>true,data:()=>({...record})}),update:(_,patch)=>{updates.push(patch);Object.assign(record,patch)}};
const params={runTransaction:async fn=>fn(tx),documentRef:{id:'alice'},getAuthenticatedUid:()=> 'alice',localAnchor:oldAnchor,now};
const one=await ensureCloudCalendar(params);
assert.equal(one.written,true);
assert.equal(record.calendarWeekAnchor,'2026-10-25');
assert.equal(record.calendarInitialWeek,2);
assert.equal(JSON.stringify(record.plan),originalPlan,'Meals must never be modified');
assert.deepEqual(Object.keys(updates[0]).sort(),['calendarInitialWeek','calendarWeekAnchor']);
const two=await ensureCloudCalendar({...params,localAnchor:new Date(2026,10,1)});
assert.equal(two.written,false);
assert.equal(dateKey(two.anchor),'2026-10-25','Other device must use cloud date');
assert.equal(updates.length,1,'Existing calendar is never overwritten');
await assert.rejects(ensureCloudCalendar({...params,getAuthenticatedUid:()=> 'bob'}),/mismatch/);
record.calendarWeekAnchor='bad-date';
await assert.rejects(ensureCloudCalendar(params),/invalid/);
console.log('PASS calendar sync, account safety, immutable meals and month boundary');
