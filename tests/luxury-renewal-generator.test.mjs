import assert from 'node:assert/strict';
import {generateRenewalCandidates} from '../luxury-v2/renewal-generator.mjs';
import {prepareRenewal} from '../luxury-v2/renewal-safety.mjs';
const saved={calendarWeekAnchor:'2026-10-25',activePlanningWeek:1,plan:{0:[null,null,'meal-00',null]},alternateWeek:{plan:{0:[null,null,'meal-01',null]}}};
const before=JSON.stringify(saved);
const recipes=Array.from({length:20},(_,i)=>({id:'meal-'+String(i).padStart(2,'0'),name:'Dinner '+i,slot:'Dinner',ingredients:['ingredient'],steps:['Cook meal']}));
const generated=generateRenewalCandidates(saved,recipes);
assert.equal(generated.selectedIds.length,14);
assert.equal(new Set(generated.selectedIds).size,14);
assert.equal(generated.repeatedFromPrevious,false);
assert.equal(generated.week1[0][2],'meal-02');
assert.equal(generated.week2[6][2],'meal-15');
const candidate=prepareRenewal(saved,generated,new Date(2026,10,8,12));
assert.equal(candidate.ok,true);
assert.equal(candidate.requiresConfirmation,true);
assert.equal(candidate.archive.plan[0][2],'meal-00');
assert.equal(candidate.proposed.plan[0][2],'meal-02');
assert.equal(JSON.stringify(saved),before);
assert.throws(()=>generateRenewalCandidates(saved,recipes.slice(0,12)),/At least 14/);
console.log('PASS deterministic 14 dinners, repeat avoidance, immutable original and renewal preview');
