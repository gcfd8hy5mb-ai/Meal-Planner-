import assert from 'node:assert/strict';
import {renewalEligibility,prepareRenewal} from '../luxury-v2/renewal-safety.mjs';
const saved={calendarWeekAnchor:'2026-10-25',calendarInitialWeek:1,activePlanningWeek:1,plan:{0:[null,null,'chicken',null]},alternateWeek:{plan:{0:[null,null,'tacos',null]}}};
const clone=JSON.stringify(saved),future=new Date(2026,10,8,12);
assert.equal(renewalEligibility(saved,new Date(2026,10,1,12)).ready,false);
assert.equal(renewalEligibility(saved,future).nextAnchor,'2026-11-08');
assert.equal(renewalEligibility(saved,new Date(2026,10,22,12)).nextAnchor,'2026-11-22');
assert.equal(renewalEligibility({...saved,calendarWeekAnchor:'bad'},future).ready,false);
assert.equal(prepareRenewal(saved,{},future).ok,false);
const generated={week1:Object.fromEntries(Array.from({length:7},(_,i)=>[i,[null,null,'beef',null]])),week2:Object.fromEntries(Array.from({length:7},(_,i)=>[i,[null,null,'fish',null]]))};
const result=prepareRenewal(saved,generated,future);
assert.equal(result.ok,true);
assert.equal(result.requiresConfirmation,true);
assert.equal(result.archive.end,'2026-11-07');
assert.equal(result.proposed.calendarWeekAnchor,'2026-11-08');
assert.equal(result.archive.plan[0][2],'chicken');
assert.equal(JSON.stringify(saved),clone,'Preparation must never overwrite saved meals');
assert.equal(result.proposed.plan[0][2],'beef');
console.log('PASS non-destructive renewal safeguard and date rollover');
