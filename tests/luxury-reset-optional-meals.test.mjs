import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {replacePreviewMeal,previewAccount} from '../luxury-v2/meal-preview.mjs';
import {searchMeals} from '../luxury-v2/meal-search.mjs';
const html=readFileSync(new URL('../luxury-v2/index.html',import.meta.url),'utf8');
const live=readFileSync(new URL('../luxury-v2/live.js',import.meta.url),'utf8');
assert.match(html,/id="luxuryForgotPassword"/);
assert.match(live,/sendPasswordResetEmail\(auth,email\)/);
assert.match(live,/const openMealPicker=\(week,day,\{initialQuick=false,slot=2\}/);
assert.match(live,/slot:mealType,quick,highProtein,lowCarb/);
assert.match(live,/openMealPicker\(active,new Date\(\)\.getDay\(\),\{slot\}\)/);
const account={activePlanningWeek:1,plan:{0:[null,null,'dinner',null]},alternateWeek:{plan:{}}};
const edit=replacePreviewMeal(account,{},1,0,0,'oats');
const edited=previewAccount(account,edit);
assert.deepEqual(edited.plan[0],['oats',null,'dinner',null]);
const more=replacePreviewMeal(account,edit,1,0,1,'sandwich');
assert.deepEqual(previewAccount(account,more).plan[0],['oats','sandwich','dinner',null]);
const meals=[{id:'oats',name:'Oats',slot:'Breakfast',ingredients:[]},{id:'sandwich',name:'Sandwich',slot:'Lunch',ingredients:[]},{id:'tacos',name:'Tacos',slot:'Dinner',ingredients:[]}];
assert.deepEqual(searchMeals(meals,{slot:'Breakfast'}).map(r=>r.id),['oats']);
assert.deepEqual(searchMeals(meals,{slot:'Lunch'}).map(r=>r.id),['sandwich']);
console.log('PASS password reset entry, breakfast/lunch filtering, and isolated meal slots');
