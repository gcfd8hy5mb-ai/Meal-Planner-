import assert from 'node:assert/strict';
import {groceryKey,checklistStorageKey,readChecklist,saveChecklist} from '../luxury-v2/checklist.mjs';
const data=new Map();
const storage={getItem:key=>data.get(key)||null,setItem:(key,val)=>data.set(key,val)};
const rows=[{name:'Rice',unit:'cup',quantity:3},{name:'Salt',unit:'tsp',quantity:1}];
assert.equal(groceryKey(rows[0]),'rice|cup');
assert.equal(readChecklist(storage,'user-a','both',rows)['rice|cup'],undefined);
assert.equal(saveChecklist(storage,'user-a','both',rows,{'rice|cup':true}),true);
assert.equal(readChecklist(storage,'user-a','both',rows)['rice|cup'],true,'Checked survives reload');
assert.deepEqual(readChecklist(storage,'user-b','both',rows),{},'Second account cannot inherit checks');
assert.deepEqual(readChecklist(storage,'user-a','1',rows),{},'Each week remains independent');
assert.deepEqual(readChecklist(storage,'user-a','both',[{...rows[0],quantity:4}]),{},'Changed ingredient quantity unchecks old completion');
assert.equal(saveChecklist(storage,'user-a','both',rows,{}),true);
assert.deepEqual(readChecklist(storage,'user-a','both',rows),{},'Uncheck all persists');
assert.equal(saveChecklist(storage,null,'both',rows,{'rice|cup':true}),false);
assert.deepEqual(readChecklist(storage,null,'both',rows),{},'Signed-out cannot load account checks');
const denied={getItem(){throw Error('Storage disabled')},setItem(){throw Error('Storage disabled')}};
assert.deepEqual(readChecklist(denied,'user-a','both',rows),{},'Private browsing unavailable storage is safe');
assert.equal(saveChecklist(denied,'user-a','both',rows,{'rice|cup':true}),false,'Storage write failure is reported');
assert.notEqual(checklistStorageKey('user-a','both'),checklistStorageKey('user-b','both'));
console.log('Luxury account-scoped local checklist tests passed');
