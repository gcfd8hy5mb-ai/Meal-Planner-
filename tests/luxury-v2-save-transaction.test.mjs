import assert from 'node:assert/strict';
import {savePreviewTransaction,PlanConflictError} from '../luxury-v2/save-transaction.mjs';
const original={activePlanningWeek:1,plan:{0:[null,null,'rice',null]},alternateWeek:{plan:{}},mealServings:{},dinnerSides:{},servings:2,mealTypes:['Dinner'],custom:['keep']};
const makeHarness=(latest=structuredClone(original),uid='athlete-a')=>{
 const calls=[];
 const ref={id:'athlete-a'};
 const tx={get:async target=>{assert.equal(target,ref);return {exists:()=>!!latest,data:()=>latest}},update:(target,fields)=>calls.push({target,fields})};
 const runTransaction=async callback=>callback(tx);
 return {calls,ref,runTransaction,getAuthenticatedUid:()=>uid};
};
let h=makeHarness();
await savePreviewTransaction({...h,documentRef:h.ref,original,preview:{'1-0-2':'beans'}});
assert.equal(h.calls.length,1,'Only one transaction update');
assert.deepEqual(Object.keys(h.calls[0].fields).sort(),['alternateWeek','plan'],'Only plan fields updated');
assert.equal(h.calls[0].fields.plan[0][2],'beans');
assert.equal(original.plan[0][2],'rice','Original account unchanged');
h=makeHarness({...structuredClone(original),plan:{0:[null,null,'other',null]}});
await assert.rejects(savePreviewTransaction({...h,documentRef:h.ref,original,preview:{'1-0-2':'beans'}}),PlanConflictError);
assert.equal(h.calls.length,0,'Concurrent change blocks all writes');
h=makeHarness(null);
await assert.rejects(savePreviewTransaction({...h,documentRef:h.ref,original,preview:{'1-0-2':'beans'}}),PlanConflictError);
assert.equal(h.calls.length,0,'Deleted account blocks all writes');
h=makeHarness(structuredClone(original),'athlete-b');
await assert.rejects(savePreviewTransaction({...h,documentRef:h.ref,original,preview:{'1-0-2':'beans'}}),/account mismatch/i);
assert.equal(h.calls.length,0,'Cross-account write denied before transaction');
h=makeHarness();
await assert.rejects(savePreviewTransaction({...h,documentRef:h.ref,original,preview:{}}),PlanConflictError);
assert.equal(h.calls.length,0,'Empty preview never writes');
let switched='athlete-a';
h=makeHarness();h.getAuthenticatedUid=()=>switched;h.runTransaction=async callback=>callback({get:async()=>{switched='athlete-b';return {exists:()=>true,data:()=>structuredClone(original)}},update:()=>{throw Error('must not update')}});
await assert.rejects(savePreviewTransaction({...h,documentRef:h.ref,original,preview:{'1-0-2':'beans'}}),/Account changed/);
console.log('Luxury transaction unit tests passed, with no live Firestore writes');
